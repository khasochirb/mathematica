#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Register every Mongolian mirror on disk with its own course module.

    python3 scripts/i18n/mn_register.py          # rewrite the generated blocks
    python3 scripts/i18n/mn_register.py --check  # exit 1 if any block is stale

Each course module (lib/genmath-data/<course>.ts, and lib/esh-course.ts for the
ЭШ-authored units) carries ONE generated block between the markers

    // MN-MIRRORS:BEGIN … // MN-MIRRORS:END

holding the imports of data/genmath/<corpus>-mn/*.json and the course-local map
`<name>: Record<slug, T>`. Course-local on purpose: the aggregator's map is keyed
by slug alone and several slugs exist in more than one course
(lib/genmath-mn-collision.test.ts). Registration is mechanical, so it is
generated; a mirror that exists is reachable, and one that does not is never
imported.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

# corpus -> (module file, map name, element type)
MODULES = {
    "6": ("lib/genmath-data/grade-6.ts", "grade6TopicsMn", "GenMathTopic"),
    "7": ("lib/genmath-data/grade-7.ts", "grade7TopicsMn", "GenMathTopic"),
    "8": ("lib/genmath-data/grade-8.ts", "grade8TopicsMn", "GenMathTopic"),
    "9": ("lib/genmath-data/grade-9.ts", "grade9TopicsMn", "GenMathTopic"),
    "10": ("lib/genmath-data/grade-10.ts", "grade10TopicsMn", "GenMathTopic"),
    "11": ("lib/genmath-data/grade-11.ts", "grade11TopicsMn", "GenMathTopic"),
    "12": ("lib/genmath-data/grade-12.ts", "grade12TopicsMn", "GenMathTopic"),
    "algebra-1": ("lib/genmath-data/algebra-1.ts", "alg1UnitsMn", "CourseUnit"),
    "algebra-2": ("lib/genmath-data/algebra-2.ts", "alg2UnitsMn", "CourseUnit"),
    "calculus": ("lib/genmath-data/calculus.ts", "calcUnitsMn", "CourseUnit"),
    "geometry": ("lib/genmath-data/geometry.ts", "geometryUnitsMn", "GeometryUnit"),
    "prob-stats": ("lib/genmath-data/prob-stats.ts", "probStatUnitsMn", "CourseUnit"),
    "solid-geometry": ("lib/genmath-data/solid-geometry.ts", "solidGeoUnitsMn", "CourseUnit"),
    "trigonometry": ("lib/genmath-data/trigonometry.ts", "trigUnitsMn", "CourseUnit"),
    "vectors-matrices": ("lib/genmath-data/vectors-matrices.ts", "vecMatUnitsMn", "CourseUnit"),
    "precalculus": ("lib/genmath-data/precalculus.ts", "precalcUnitsMn", "CourseUnit"),
    "integrated-1": ("lib/genmath-data/integrated-1.ts", "im1UnitsMn", "CourseUnit"),
    "integrated-2": ("lib/genmath-data/integrated-2.ts", "im2UnitsMn", "CourseUnit"),
    "integrated-3": ("lib/genmath-data/integrated-3.ts", "im3UnitsMn", "CourseUnit"),
    "esh": ("lib/esh-course.ts", "eshAuthoredMn", "CourseUnit"),
}
BEGIN = "// MN-MIRRORS:BEGIN"
END = "// MN-MIRRORS:END"


def ident(corpus, slug):
    parts = re.split(r"[^A-Za-z0-9]+", f"{corpus} {slug}")
    return "mn" + "".join(p[:1].upper() + p[1:] for p in parts if p)


def block(corpus, name, typ):
    d = os.path.join(ROOT, "data", "genmath", f"{corpus}-mn")
    slugs = sorted(f[:-5] for f in os.listdir(d) if f.endswith(".json")) if os.path.isdir(d) else []
    cast = f"as unknown as {typ}"
    lines = [f"{BEGIN} (generated by scripts/i18n/mn_register.py; do not edit by hand)"]
    for s in slugs:
        lines.append(f'import {ident(corpus, s)} from "@/data/genmath/{corpus}-mn/{s}.json";')
    if slugs:
        lines.append(f"export const {name}: Record<string, {typ}> = {{")
        for s in slugs:
            lines.append(f'  "{s}": {ident(corpus, s)} {cast},')
        lines.append("};")
    else:
        lines.append(f"export const {name}: Record<string, {typ}> = {{}};")
    lines.append(END)
    return "\n".join(lines)


def render(src, corpus, name, typ):
    new = block(corpus, name, typ)
    if BEGIN in src:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: new, src, flags=re.S)
    # first run: put it after the last top-level import
    lines = src.split("\n")
    last = max(i for i, l in enumerate(lines) if l.startswith("import "))
    while not lines[last].rstrip().endswith(";"):
        last += 1
    lines.insert(last + 1, "\n" + new)
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    stale = []
    for corpus, (rel, name, typ) in MODULES.items():
        p = os.path.join(ROOT, rel)
        src = open(p, encoding="utf-8").read()
        out = render(src, corpus, name, typ)
        if out != src:
            stale.append(rel)
            if not check:
                open(p, "w", encoding="utf-8").write(out)
    if check:
        if stale:
            print("stale MN registration:", ", ".join(stale))
            return 1
        print("MN registration up to date")
        return 0
    print(f"rewrote {len(stale)} module(s)" + (": " + ", ".join(stale) if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
