#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Mongolian course exams, generated from the Mongolian problem-bank mirrors.

    python3 scripts/i18n/mn_exams.py          # write every exam whose course mirror is complete
    python3 scripts/i18n/mn_exams.py --check  # report coverage, write nothing

WHY NO TABLE. Every course-exam question is a problem-bank variant: same id,
same statement, options, explanation and figure (asserted below on every run).
So the Mongolian exam is the Mongolian bank variant, looked up by id. Writing
it again would give the same question two Mongolian wordings. The only new
text is the paper's meta (course title, label, intro), in
i18n/exam-meta.mn.json.

An exam is written only when EVERY one of its questions has a Mongolian
variant; a half-Mongolian paper is worse than an English one. Output:
data/course-exams-mn/<examId>.json plus the registry lib/course-exam-mn.ts.
The mirror copies ids, correctIndex and check[] from the English, so scoring
and verify are untouched. Never hand-edit the output; rerun this.
"""
import copy
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EN_DIR = os.path.join(ROOT, "data", "course-exams")
OUT = os.path.join(ROOT, "data", "course-exams-mn")
BANK_EN = os.path.join(ROOT, "data", "problembank")
BANK_MN = os.path.join(ROOT, "data", "problembank-mn")
META = os.path.join(ROOT, "i18n", "exam-meta.mn.json")
REGISTRY = os.path.join(ROOT, "lib", "course-exam-mn.ts")


def bank_index(path):
    """variant id -> (form, variant, unit title) for one bank file."""
    if not os.path.exists(path):
        return {}
    d = json.load(open(path, encoding="utf-8"))
    units = {u["id"]: u["title"] for u in d["units"]}
    out = {}
    for f in d["forms"]:
        for v in f["variants"]:
            out[v["id"]] = (f, v, units.get(f["unit"]))
    return out


def build(exam, en_bank, mn_bank, meta):
    """The Mongolian exam, or (None, reason)."""
    m = exam["meta"]
    course = meta["courses"].get(m["course"])
    if not course:
        return None, "no meta for course"
    missing = [q["id"] for q in exam["questions"] if q["id"] not in mn_bank]
    if missing:
        return None, f"{len(missing)} question(s) not yet in the Mongolian bank"
    out = copy.deepcopy(exam)
    n = re.search(r"(\d+)$", m["examId"]).group(1)
    out["meta"]["courseTitle"] = course["courseTitle"]
    out["meta"]["intro"] = course["intro"]
    out["meta"]["label"] = meta["label"].replace("{course}", course["courseTitle"]).replace("{n}", n)
    for q in out["questions"]:
        ef, ev, _ = en_bank[q["id"]]
        # The premise of this script: the exam question IS the bank variant.
        for k in ("statement", "options", "explanation", "correctIndex"):
            if q[k] != ev[k]:
                raise SystemExit(f"{m['examId']} {q['id']}: {k} differs from the bank; cannot derive")
        if q.get("geoFigure") != ev.get("geoFigure"):
            raise SystemExit(f"{m['examId']} {q['id']}: figure differs from the bank")
        f, v, unit_title = mn_bank[q["id"]]
        if v["correctIndex"] != q["correctIndex"] or len(v["options"]) != len(q["options"]):
            raise SystemExit(f"{m['examId']} {q['id']}: Mongolian variant disagrees on the key")
        q["statement"] = v["statement"]
        q["options"] = v["options"]
        q["explanation"] = v["explanation"]
        q["skill"] = f["skill"]
        if unit_title:
            q["unitTitle"] = unit_title
        if v.get("geoFigure"):
            q["geoFigure"] = v["geoFigure"]
    return out, None


def ident(exam_id):
    return "x" + re.sub(r"[^A-Za-z0-9]", "_", exam_id)


def write_registry(ids):
    lines = [
        "// GENERATED by scripts/i18n/mn_exams.py — do not edit by hand.",
        "// Mongolian course exams, keyed by examId. An exam is listed only when every",
        "// question has a Mongolian bank variant; anything else falls back to English.",
        'import type { CourseExam } from "@/lib/course-exam";',
        "",
    ]
    for i in ids:
        lines.append(f'import {ident(i)} from "@/data/course-exams-mn/{i}.json";')
    lines += ["", "export const EXAMS_MN: Record<string, CourseExam> = {"]
    for i in ids:
        lines.append(f'  "{i}": {ident(i)} as unknown as CourseExam,')
    lines += ["};", ""]
    with open(REGISTRY, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    check_only = "--check" in sys.argv
    meta = json.load(open(META, encoding="utf-8"))
    banks = {}
    written = []
    for p in sorted(glob.glob(os.path.join(EN_DIR, "*.json"))):
        exam = json.load(open(p, encoding="utf-8"))
        c = exam["meta"]["course"]
        if c not in banks:
            banks[c] = (bank_index(os.path.join(BANK_EN, f"{c}.json")),
                        bank_index(os.path.join(BANK_MN, f"{c}.json")))
        out, why = build(exam, *banks[c], meta)
        eid = exam["meta"]["examId"]
        if out is None:
            print(f"skip  {eid}: {why}")
            continue
        written.append(eid)
        print(f"ok    {eid}: {len(out['questions'])} questions")
        if not check_only:
            os.makedirs(OUT, exist_ok=True)
            with open(os.path.join(OUT, f"{eid}.json"), "w", encoding="utf-8") as fh:
                json.dump(out, fh, ensure_ascii=False, indent=1)
                fh.write("\n")
    if not check_only:
        # Drop stale outputs so the registry and the directory agree.
        for p in glob.glob(os.path.join(OUT, "*.json")):
            if os.path.basename(p)[:-5] not in written:
                os.remove(p)
        write_registry(written)
        print(f"registered {len(written)} exam(s) in lib/course-exam-mn.ts")


if __name__ == "__main__":
    main()
