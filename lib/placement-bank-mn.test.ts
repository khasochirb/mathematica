import { describe, it, expect } from "vitest";
import {
  PLACEMENT_BANKS,
  getPlacementBankMn,
  localizePlacementBank,
  type PlacementBankId,
} from "./placement-bank-mn";

// The gate on the Mongolian grade-placement tables (i18n/placement-tables/).
// A table rewrites the WORDS of a question; everything that decides whether
// an answer is right stays byte-for-byte the English:
//
//   - every `$…$` segment of the English prompt and explanation reappears in
//     the Mongolian one (the Mongolian may add a bare one-letter variable,
//     `$x$`, where the English wrote "x-axis" in prose, and nothing else);
//   - every digit the English prompt writes OUTSIDE maths («6 h») is still
//     there outside maths;
//   - same option count, same order; an option that is pure maths
//     (`$\tfrac{3}{4}$`) is identical (correctIndex is never in the table);
//   - no Cyrillic inside maths except inside \text{…};
//   - no English left in the prose (single Latin letters and Roman numerals
//     are symbols, not words), no decimal point in prose (decimal COMMA,
//     docs/mn-voice-reference.md §7), no em-dash asides (§9).

/** Banks whose table must cover every question. Add yours when it is done. */
const COMPLETE: PlacementBankId[] = ["6", "geometry"];

/** `$…$` segments, honouring `\$` (a literal dollar sign inside maths). */
function mathSegments(s: string): string[] {
  const out: string[] = [];
  let i = 0;
  let open = -1;
  while (i < s.length) {
    if (s[i] === "\\" && s[i + 1] === "$") { i += 2; continue; }
    if (s[i] === "$") {
      if (open < 0) open = i;
      else { out.push(s.slice(open + 1, i)); open = -1; }
    }
    i++;
  }
  if (open >= 0) out.push(`UNCLOSED:${s.slice(open)}`);
  return out;
}

/** The prose: the string with every `$…$` segment removed. */
function prose(s: string): string {
  let out = "";
  let i = 0;
  let inMath = false;
  while (i < s.length) {
    if (s[i] === "\\" && s[i + 1] === "$") { if (!inMath) out += "$"; i += 2; continue; }
    if (s[i] === "$") { inMath = !inMath; out += " "; i++; continue; }
    if (!inMath) out += s[i];
    i++;
  }
  return out;
}

const count = (xs: string[]) => {
  const m = new Map<string, number>();
  for (const x of xs) m.set(x, (m.get(x) ?? 0) + 1);
  return m;
};

/** Problems with `mn`'s maths against `en`'s: missing segments, or extras that are not a bare letter. */
function mathDrift(en: string, mn: string): string[] {
  const e = count(mathSegments(en));
  const m = count(mathSegments(mn));
  const bad: string[] = [];
  for (const [seg, n] of Array.from(e)) {
    if ((m.get(seg) ?? 0) < n) bad.push(`missing $${seg}$`);
  }
  for (const [seg, n] of Array.from(m)) {
    if (n > (e.get(seg) ?? 0) && !/^[A-Za-z]$/.test(seg.trim())) bad.push(`added $${seg}$`);
  }
  return bad;
}

const digitsOutsideMath = (s: string) => (prose(s).match(/\d/g) ?? []).sort().join("");
const isMathOnly = (s: string) => /^\$[^$]*\$$/.test(s.trim()) && mathSegments(s.trim()).length === 1;
const CYRILLIC = /[Ѐ-ӿ]/;

function cyrillicInMath(s: string): string[] {
  return mathSegments(s)
    .map((seg) => seg.replace(/\\text\{[^{}]*\}/g, ""))
    .filter((seg) => CYRILLIC.test(seg));
}

function englishWords(s: string): string[] {
  return (prose(s).match(/[A-Za-z]{2,}/g) ?? []).filter((w) => !/^[IVXLC]+$/.test(w));
}

function proseStyle(s: string): string[] {
  const p = prose(s);
  const bad: string[] = [];
  if (/\d\.\d/.test(p)) bad.push("decimal point in prose");
  if (p.includes("—")) bad.push("em dash");
  return bad;
}

const ids = Object.keys(PLACEMENT_BANKS) as PlacementBankId[];

describe("placement tables: shape", () => {
  for (const id of ids) {
    const { en, table } = PLACEMENT_BANKS[id];
    const bank = en();
    const byId = new Map(bank.map((q) => [q.id, q]));

    it(`${id}: topics cover the bank's slugs exactly (generated by mn_placement_topics.py)`, () => {
      const slugs = Array.from(new Set(bank.map((q) => q.topicSlug))).sort();
      expect(Object.keys(table.topics).sort()).toEqual(slugs);
      for (const t of Object.values(table.topics)) expect(CYRILLIC.test(t)).toBe(true);
    });

    it(`${id}: every question key is a real question id of this bank`, () => {
      for (const k of Object.keys(table.questions)) expect(byId.has(k), `${id}: stray ${k}`).toBe(true);
    });

    if (COMPLETE.includes(id)) {
      it(`${id}: every question is written`, () => {
        const missing = bank.filter((q) => !table.questions[q.id]).map((q) => q.id);
        expect(missing).toEqual([]);
      });
    }
  }
});

describe("placement tables: maths and answer key held fixed", () => {
  for (const id of ids) {
    const { en, table } = PLACEMENT_BANKS[id];
    const byId = new Map(en().map((q) => [q.id, q]));
    for (const [qid, t] of Object.entries(table.questions)) {
      const q = byId.get(qid);
      if (!q) continue; // reported by the shape test
      it(`${id} ${qid}`, () => {
        const where = `${id} ${qid}`;
        expect(typeof t.prompt, where).toBe("string");
        expect(typeof t.explanation, where).toBe("string");
        expect(t.prompt.trim().length, `${where} prompt`).toBeGreaterThan(0);
        expect(t.explanation.trim().length, `${where} explanation`).toBeGreaterThan(0);

        expect(mathDrift(q.prompt, t.prompt), `${where} prompt maths`).toEqual([]);
        expect(mathDrift(q.explanation, t.explanation), `${where} explanation maths`).toEqual([]);
        expect(digitsOutsideMath(t.prompt), `${where} prompt digits outside maths`).toBe(digitsOutsideMath(q.prompt));

        expect(t.options.length, `${where} option count`).toBe(q.options.length);
        t.options.forEach((o, i) => {
          const eo = q.options[i];
          if (isMathOnly(eo)) expect(o, `${where} option ${i} is maths-only`).toBe(eo);
          else expect(mathDrift(eo, o), `${where} option ${i} maths`).toEqual([]);
        });

        for (const s of [t.prompt, t.explanation, ...t.options]) {
          expect(cyrillicInMath(s), `${where} Cyrillic in maths: ${s}`).toEqual([]);
          expect(englishWords(s), `${where} English left: ${s}`).toEqual([]);
          expect(proseStyle(s), `${where} style: ${s}`).toEqual([]);
        }
      });
    }
  }
});

describe("getPlacementBankMn", () => {
  for (const id of ids) {
    it(`${id}: same ids, order, answer key and slugs as the English bank`, () => {
      const en = PLACEMENT_BANKS[id].en();
      const mn = getPlacementBankMn(id);
      expect(mn.map((q) => q.id)).toEqual(en.map((q) => q.id));
      expect(mn.map((q) => q.correctIndex)).toEqual(en.map((q) => q.correctIndex));
      expect(mn.map((q) => q.topicSlug)).toEqual(en.map((q) => q.topicSlug));
      expect(mn.map((q) => q.difficulty)).toEqual(en.map((q) => q.difficulty));
    });
  }

  it("falls back to English per question, and on an option-count mismatch", () => {
    const en = PLACEMENT_BANKS["6"].en().slice(0, 2);
    const out = localizePlacementBank(en, {
      topics: {},
      questions: { [en[1].id]: { prompt: "П", options: ["a"], explanation: "Т" } },
    });
    expect(out[0].prompt).toBe(en[0].prompt);
    expect(out[1].prompt).toBe(en[1].prompt);
  });
});
