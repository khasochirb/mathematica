import type { CourseUnit, GenMathLesson } from "@/lib/genmath-types";
import { IM1_SPINE, type GeometrySpineEntry } from "@/lib/genmath-spines";

import im1Quantities from "@/data/genmath/integrated-1/quantities-and-expressions.json";
import im1LinearEq from "@/data/genmath/integrated-1/linear-equations-and-inequalities.json";
import im1Functions from "@/data/genmath/integrated-1/functions-and-sequences.json";
import im1LinearFn from "@/data/genmath/integrated-1/linear-functions.json";
import im1Systems from "@/data/genmath/integrated-1/systems-of-equations-and-inequalities.json";
import im1Exponential from "@/data/genmath/integrated-1/exponential-functions.json";
import im1Transformations from "@/data/genmath/integrated-1/transformations-and-congruence.json";
import im1CoordGeo from "@/data/genmath/integrated-1/coordinate-geometry.json";
import im1Data from "@/data/genmath/integrated-1/data-and-statistics.json";

// MN-MIRRORS:BEGIN (generated by scripts/i18n/mn_register.py; do not edit by hand)
import mnIntegrated1CoordinateGeometry from "@/data/genmath/integrated-1-mn/coordinate-geometry.json";
import mnIntegrated1ExponentialFunctions from "@/data/genmath/integrated-1-mn/exponential-functions.json";
import mnIntegrated1FunctionsAndSequences from "@/data/genmath/integrated-1-mn/functions-and-sequences.json";
import mnIntegrated1LinearEquationsAndInequalities from "@/data/genmath/integrated-1-mn/linear-equations-and-inequalities.json";
import mnIntegrated1LinearFunctions from "@/data/genmath/integrated-1-mn/linear-functions.json";
import mnIntegrated1SystemsOfEquationsAndInequalities from "@/data/genmath/integrated-1-mn/systems-of-equations-and-inequalities.json";
export const im1UnitsMn: Record<string, CourseUnit> = {
  "coordinate-geometry": mnIntegrated1CoordinateGeometry as unknown as CourseUnit,
  "exponential-functions": mnIntegrated1ExponentialFunctions as unknown as CourseUnit,
  "functions-and-sequences": mnIntegrated1FunctionsAndSequences as unknown as CourseUnit,
  "linear-equations-and-inequalities": mnIntegrated1LinearEquationsAndInequalities as unknown as CourseUnit,
  "linear-functions": mnIntegrated1LinearFunctions as unknown as CourseUnit,
  "systems-of-equations-and-inequalities": mnIntegrated1SystemsOfEquationsAndInequalities as unknown as CourseUnit,
};
// MN-MIRRORS:END

const im1Units: CourseUnit[] = [
  im1Quantities as unknown as CourseUnit,
  im1LinearEq as unknown as CourseUnit,
  im1Functions as unknown as CourseUnit,
  im1LinearFn as unknown as CourseUnit,
  im1Systems as unknown as CourseUnit,
  im1Exponential as unknown as CourseUnit,
  im1Transformations as unknown as CourseUnit,
  im1CoordGeo as unknown as CourseUnit,
  im1Data as unknown as CourseUnit,
];

export function getIm1Spine(): GeometrySpineEntry[] {
  return IM1_SPINE;
}

export function getIm1Unit(unitSlug: string): CourseUnit | null {
  return im1Units.find((u) => u.slug === unitSlug) ?? null;
}

export function getIm1Lesson(
  unitSlug: string,
  lessonSlug: string
): GenMathLesson | null {
  const unit = getIm1Unit(unitSlug);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}

// Locale-aware lookups, scoped to this course: the Mongolian mirror when the
// site language is "mn" and one exists (scripts/i18n/mn_register.py keeps
// im1UnitsMn in step with data/genmath/integrated-1-mn/), the English unit otherwise.
export function getIm1UnitLocalized(unitSlug: string, lang: string): CourseUnit | null {
  if (lang === "mn" && im1UnitsMn[unitSlug]) return im1UnitsMn[unitSlug];
  return getIm1Unit(unitSlug);
}

export function getIm1LessonLocalized(
  unitSlug: string,
  lessonSlug: string,
  lang: string
): GenMathLesson | null {
  const unit = getIm1UnitLocalized(unitSlug, lang);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}
