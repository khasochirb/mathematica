const vecMatUnits: CourseUnit[] = [
  vmVectorsCoords as unknown as CourseUnit,
  vmArithmetic as unknown as CourseUnit,
  vmDotProduct as unknown as CourseUnit,
  vmSpace as unknown as CourseUnit,
  vmMatrices as unknown as CourseUnit,
  vmDeterminants as unknown as CourseUnit,
  vmTransformations as unknown as CourseUnit,
  vmThreeUnknowns as unknown as CourseUnit,
];

export function getVecMatSpine(): GeometrySpineEntry[] {
  return VECMAT_SPINE;
}

export function getVecMatUnit(unitSlug: string): CourseUnit | null {
  return vecMatUnits.find((u) => u.slug === unitSlug) ?? null;
}

export function getVecMatLesson(
  unitSlug: string,
  lessonSlug: string
): GenMathLesson | null {
  const unit = getVecMatUnit(unitSlug);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}

// Locale-aware lookups, scoped to this course: the Mongolian mirror when the
// site language is "mn" and one exists (scripts/i18n/mn_register.py keeps
// vecMatUnitsMn in step with data/genmath/vectors-matrices-mn/), the English unit otherwise.
export function getVecMatUnitLocalized(unitSlug: string, lang: string): CourseUnit | null {
  if (lang === "mn" && vecMatUnitsMn[unitSlug]) return vecMatUnitsMn[unitSlug];
  return getVecMatUnit(unitSlug);
}

export function getVecMatLessonLocalized(
  unitSlug: string,
  lessonSlug: string,
  lang: string
): GenMathLesson | null {
  const unit = getVecMatUnitLocalized(unitSlug, lang);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}
