// Trig course data — /math/trigonometry. One course's corpus and nothing else,
// so this course's pages bundle ONLY their own content (the aggregator in
// lib/genmath-lessons.ts imports every course for the cross-course
// consumers; pages must import from HERE — lib/genmath-split.test.ts).

import type { CourseUnit, GenMathLesson } from "@/lib/genmath-types";
import { TRIG_SPINE, type GeometrySpineEntry } from "@/lib/genmath-spines";

import trigRight from "@/data/genmath/trigonometry/right-triangle-trigonometry.json";
import trigSpecial from "@/data/genmath/trigonometry/special-triangles-and-exact-values.json";
import trigCircle from "@/data/genmath/trigonometry/radians-and-the-unit-circle.json";
import trigGraphs from "@/data/genmath/trigonometry/graphs-of-trig-functions.json";
import trigIdent from "@/data/genmath/trigonometry/identities-and-equations.json";
import trigLaws from "@/data/genmath/trigonometry/laws-of-sines-and-cosines.json";

// MN-MIRRORS:BEGIN (generated by scripts/i18n/mn_register.py; do not edit by hand)
import mnTrigonometryGraphsOfTrigFunctions from "@/data/genmath/trigonometry-mn/graphs-of-trig-functions.json";
import mnTrigonometryIdentitiesAndEquations from "@/data/genmath/trigonometry-mn/identities-and-equations.json";
import mnTrigonometryLawsOfSinesAndCosines from "@/data/genmath/trigonometry-mn/laws-of-sines-and-cosines.json";
import mnTrigonometryRadiansAndTheUnitCircle from "@/data/genmath/trigonometry-mn/radians-and-the-unit-circle.json";
import mnTrigonometryRightTriangleTrigonometry from "@/data/genmath/trigonometry-mn/right-triangle-trigonometry.json";
import mnTrigonometrySpecialTrianglesAndExactValues from "@/data/genmath/trigonometry-mn/special-triangles-and-exact-values.json";
export const trigUnitsMn: Record<string, CourseUnit> = {
  "graphs-of-trig-functions": mnTrigonometryGraphsOfTrigFunctions as unknown as CourseUnit,
  "identities-and-equations": mnTrigonometryIdentitiesAndEquations as unknown as CourseUnit,
  "laws-of-sines-and-cosines": mnTrigonometryLawsOfSinesAndCosines as unknown as CourseUnit,
  "radians-and-the-unit-circle": mnTrigonometryRadiansAndTheUnitCircle as unknown as CourseUnit,
  "right-triangle-trigonometry": mnTrigonometryRightTriangleTrigonometry as unknown as CourseUnit,
  "special-triangles-and-exact-values": mnTrigonometrySpecialTrianglesAndExactValues as unknown as CourseUnit,
};
// MN-MIRRORS:END

const trigUnits: CourseUnit[] = [
  trigRight as unknown as CourseUnit,
  trigSpecial as unknown as CourseUnit,
  trigCircle as unknown as CourseUnit,
  trigGraphs as unknown as CourseUnit,
  trigIdent as unknown as CourseUnit,
  trigLaws as unknown as CourseUnit,
];

export function getTrigSpine(): GeometrySpineEntry[] {
  return TRIG_SPINE;
}

export function getTrigUnit(unitSlug: string): CourseUnit | null {
  return trigUnits.find((u) => u.slug === unitSlug) ?? null;
}

export function getTrigLesson(
  unitSlug: string,
  lessonSlug: string
): GenMathLesson | null {
  const unit = getTrigUnit(unitSlug);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}

// Locale-aware lookups, scoped to this course: the Mongolian mirror when the
// site language is "mn" and one exists (scripts/i18n/mn_register.py keeps
// trigUnitsMn in step with data/genmath/trigonometry-mn/), the English unit otherwise.
export function getTrigUnitLocalized(unitSlug: string, lang: string): CourseUnit | null {
  if (lang === "mn" && trigUnitsMn[unitSlug]) return trigUnitsMn[unitSlug];
  return getTrigUnit(unitSlug);
}

export function getTrigLessonLocalized(
  unitSlug: string,
  lessonSlug: string,
  lang: string
): GenMathLesson | null {
  const unit = getTrigUnitLocalized(unitSlug, lang);
  if (!unit) return null;
  return unit.lessons.find((l) => l.slug === lessonSlug) ?? null;
}
